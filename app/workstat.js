export const HOL_UPTO = '2027-12-31';   // 이 뒤 해는 목록을 더해야 함 (월력요항 6월 발표)

const pad = n => ('0' + n).slice(-2);
const dowOf = s => new Date(s + 'T00:00:00Z').getUTCDay();

/** days = {날짜: {a: 배정 유닛, d: 완료 유닛}}, ym = 'YYYY-MM', today = 'YYYY-MM-DD' */
export function workStat(days, ym, today) {
  const y = Number(ym.slice(0, 4)), m = Number(ym.slice(5, 7)), last = new Date(Date.UTC(y, m, 0)).getUTCDate();
  const cur = today.slice(0, 7) === ym;
  let weekend = 0, passed = 0, work = 0, ot = 0, plus = 0, minus = 0;
  const hol = [];
  for (let k = 1; k <= last; k++) {
    const ds = ym + '-' + pad(k), w = dowOf(ds), o = days[ds];
    if (w === 0 || w === 6) weekend++;
    const worked = !!(o && Number(o.a) > 0);
    if (cur && ds > today) continue;
    if (cur && ds === today && !worked) continue;   // 오늘 아직 배정이 없으면 쉰 날로 세지 않음
    passed++;
    if (!worked) continue;
    work++;
    if (HOL[ds]) hol.push({ day: ds, name: HOL[ds] });
    const u = Math.round(Number(o.a) * 10) / 10, x = u - 9;
    ot += x; if (x > 0) plus++; else if (x < 0) minus++;
  }
  const rest = passed - work;
  ot = Math.round(ot * 10) / 10;
  return {
    ym, cur, weekend, work, rest,
    left: weekend - rest,                                   // 남은 휴무 (이번 달: 이만큼 더 쉬어도 연차 안 씀 · 지난달: 특근)
    extra: cur ? 0 : Math.max(0, weekend - rest),           // 특근 (달이 끝나야 정해짐)
    fill: Math.max(0, rest - weekend),                      // 보유 휴무보다 더 쉰 날 = 연차로 채울 날
    hol, ot: Math.max(0, ot), otRaw: ot, plus, minus,
    known: ym <= HOL_UPTO.slice(0, 7)
  };
}
